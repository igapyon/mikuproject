import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";
import { build } from "esbuild";

export const JSON_SCHEMA_2020_12 = "https://json-schema.org/draft/2020-12/schema";
export const GENERATED_VALIDATOR_RELATIVE_PATH = "scripts/generated/cli-v1-schema-validators.mjs";

export const SCHEMA_REGISTRY = Object.freeze([
  Object.freeze({
    key: "artifact",
    exportName: "validateArtifact",
    id: "urn:miku-project:schema:artifacts:v1",
    relativePath: "docs/schemas/miku-project-artifacts-v1.schema.json"
  }),
  Object.freeze({
    key: "cliDiagnostic",
    exportName: "validateCliDiagnostic",
    id: "urn:miku-project:schema:cli-diagnostic:v1",
    relativePath: "docs/schemas/miku-project-cli-diagnostic-v1.schema.json"
  }),
  Object.freeze({
    key: "cliResult",
    exportName: "validateCliResult",
    id: "urn:miku-project:schema:cli-result:v1",
    relativePath: "docs/schemas/miku-project-cli-result-v1.schema.json"
  }),
  Object.freeze({
    key: "runtimeManifest",
    exportName: "validateRuntimeManifest",
    id: "urn:miku-project:schema:runtime-manifest:v1",
    relativePath: "docs/schemas/miku-project-runtime-manifest-v1.schema.json"
  })
]);

const MODULE_DIRECTORY = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_ROOT_DIRECTORY = path.resolve(MODULE_DIRECTORY, "../../..");

export async function generateCliV1SchemaValidators({ rootDirectory = DEFAULT_ROOT_DIRECTORY } = {}) {
  const registry = readSchemaRegistry({ rootDirectory });
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    // Existing approved schemas express some conditional branches through
    // properties and $defs constrained by an enclosing schema. Ajv cannot
    // infer those enclosing declarations in each branch, so keep strict
    // schema checks while disabling only these authoring-style warnings.
    strictRequired: false,
    strictTuples: false,
    strictTypes: false,
    validateFormats: true,
    code: {
      esm: true,
      lines: true,
      source: true
    }
  });
  addFormats(ajv);

  for (const entry of registry) {
    ajv.addSchema(entry.schema);
  }

  const validatorReferences = {};
  for (const entry of registry) {
    if (!ajv.getSchema(entry.id)) {
      throw new Error(`schema registry did not compile ${entry.id}`);
    }
    validatorReferences[entry.exportName] = entry.id;
  }

  const standaloneSource = standaloneCode(ajv, validatorReferences);
  const bundled = await build({
    absWorkingDir: path.resolve(rootDirectory),
    bundle: true,
    format: "esm",
    legalComments: "none",
    minify: false,
    platform: "node",
    sourcemap: false,
    target: "node20",
    write: false,
    stdin: {
      contents: standaloneSource,
      loader: "js",
      // The validator source is materialized against an arbitrary schema
      // root in drift tests. Resolve only build-time packages from this
      // generator's repository, never from that materialized root.
      resolveDir: DEFAULT_ROOT_DIRECTORY,
      sourcefile: "cli-v1-schema-validators-standalone.mjs"
    }
  });

  if (bundled.outputFiles.length !== 1) {
    throw new Error(`expected one generated validator output, received ${bundled.outputFiles.length}`);
  }

  const source = [
    "// Generated by scripts/generate-cli-v1-schema-validators.mjs. Do not edit manually.",
    "// Source schemas: docs/schemas/miku-project-*-v1.schema.json",
    bundled.outputFiles[0].text.trimEnd(),
    ""
  ].join("\n");
  assertStandaloneEsm(source, rootDirectory);
  return source;
}

export async function writeCliV1SchemaValidators({ rootDirectory = DEFAULT_ROOT_DIRECTORY } = {}) {
  const outputPath = resolveOutputPath(rootDirectory);
  const source = await generateCliV1SchemaValidators({ rootDirectory });
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, source, "utf8");
  return { outputPath, source };
}

export async function checkCliV1SchemaValidators({ rootDirectory = DEFAULT_ROOT_DIRECTORY } = {}) {
  const outputPath = resolveOutputPath(rootDirectory);
  const expectedSource = await generateCliV1SchemaValidators({ rootDirectory });
  const actualSource = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : null;
  if (actualSource !== expectedSource) {
    throw new Error(
      `generated CLI v1 schema validators are out of date: run npm run generate:cli-v1-schema-validators (${path.relative(path.resolve(rootDirectory), outputPath)})`
    );
  }
  return { outputPath, source: actualSource };
}

export function readSchemaRegistry({ rootDirectory = DEFAULT_ROOT_DIRECTORY } = {}) {
  const seenIds = new Set();
  const knownIds = new Set(SCHEMA_REGISTRY.map((entry) => entry.id));
  const registry = SCHEMA_REGISTRY.map((definition) => {
    const schemaPath = path.resolve(rootDirectory, definition.relativePath);
    if (!fs.existsSync(schemaPath)) {
      throw new Error(`schema registry source is missing: ${definition.relativePath}`);
    }
    const schema = JSON.parse(fs.readFileSync(schemaPath, "utf8"));
    if (schema.$schema !== JSON_SCHEMA_2020_12) {
      throw new Error(`schema ${definition.relativePath} must declare ${JSON_SCHEMA_2020_12}`);
    }
    if (schema.$id !== definition.id) {
      throw new Error(`schema ${definition.relativePath} has unexpected $id: ${String(schema.$id)}`);
    }
    if (seenIds.has(schema.$id)) {
      throw new Error(`schema registry has duplicate $id: ${schema.$id}`);
    }
    seenIds.add(schema.$id);
    return { ...definition, schema };
  });

  for (const entry of registry) {
    for (const reference of collectExternalReferences(entry.schema)) {
      const referencedId = reference.split("#", 1)[0];
      if (!knownIds.has(referencedId)) {
        throw new Error(`schema ${entry.relativePath} has unresolved external $ref: ${reference}`);
      }
    }
  }
  return registry;
}

function resolveOutputPath(rootDirectory) {
  return path.resolve(rootDirectory, GENERATED_VALIDATOR_RELATIVE_PATH);
}

function collectExternalReferences(value, references = []) {
  if (Array.isArray(value)) {
    for (const item of value) {
      collectExternalReferences(item, references);
    }
    return references;
  }
  if (!value || typeof value !== "object") {
    return references;
  }
  for (const [key, item] of Object.entries(value)) {
    if (key === "$ref" && typeof item === "string" && !item.startsWith("#")) {
      references.push(item);
    } else {
      collectExternalReferences(item, references);
    }
  }
  return references;
}

function assertStandaloneEsm(source, rootDirectory) {
  if (/^\s*import\s/m.test(source) || /^\s*export\s+.+?\s+from\s/m.test(source)) {
    throw new Error("generated CLI v1 schema validators must not retain runtime imports");
  }
  if (source.includes(path.resolve(rootDirectory))) {
    throw new Error("generated CLI v1 schema validators must not embed an absolute generator path");
  }
}
